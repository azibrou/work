// Writes the story files whose names come from the top navigation:
//   src/pages/Pages.stories.jsx                     Pages/<page name>, one story per page
//   src/components/home-cards/<Page>.stories.jsx    Components/Cards/<page name>, one story per card
// A page's name is the label of the first top-navigation item that opens it,
// else its own name from pages.json (pageLabel). Storybook needs story names
// written out in the file, so they are generated: at startup (main.js) and
// whenever the top navigation or pages are applied (tokenSavePlugin.js).
// The files are committed so Storybook finds them even before this runs; don't
// edit them by hand.

import fs from 'node:fs';
import path from 'node:path';
import { PAGE_CONTENT as DEFAULT_CONTENT, pageLabel } from '../src/pages/pageContent.js';

const root = path.resolve(import.meta.dirname, '..');
const pagesDir = path.join(root, 'src/pages');
const cardsDir = path.join(root, 'src/components/home-cards');
const CARD_FILE = /^Cards[A-Z][A-Za-z0-9]*\.stories\.jsx$/;
const menuFile = path.join(root, 'src/components/top-menu/menu.json');
const pagesFile = path.join(root, 'src/pages/pages.json');

const HEADER = '// Generated by .storybook/generateStories.js from menu.json, pages.json and pageContent.js. Do not edit.\n';
const readJson = (file) => JSON.parse(fs.readFileSync(file, 'utf8'));

// "uvLightSensor" / "my-page" → "UvLightSensor" / "MyPage": a valid, unique export name.
function exportName(key, taken) {
  const base = String(key)
    .replace(/[^a-zA-Z0-9]+(.)?/g, (_, c) => (c ? c.toUpperCase() : ''))
    .replace(/^[^a-zA-Z_]+/, '')
    .replace(/^./, (c) => c.toUpperCase()) || 'Story';
  let name = base;
  for (let n = 2; taken.has(name); n += 1) name = `${base}${n}`;
  taken.add(name);
  return name;
}

// Pages in top-navigation order, then the pages no item opens.
function orderedPages(menu, pages) {
  const linked = menu.items.map((item) => item.page);
  const ids = pages.pages.map((p) => p.id);
  return [...new Set([...linked.filter((id) => ids.includes(id)), ...ids])];
}

/** The generated files as { fileName: source }. Pure, for tests. */
export function buildStoryFiles({ menu, pages, content = DEFAULT_CONTENT }) {
  const order = orderedPages(menu, pages);
  const files = {};

  const taken = new Set();
  const pageStories = order.map((id) => {
    const name = exportName(id, taken);
    return `export const ${name} = { name: ${JSON.stringify(pageLabel(id, menu, pages))}, render: (args) => <PageStory pageId=${JSON.stringify(id)} args={args} /> };`;
  });
  files['pages/Pages.stories.jsx'] = `${HEADER}import PageStory from './storybook/PageStory.jsx';
import { transitionArgs, transitionArgTypes } from '../transitions/storybook/controls.js';

// Each page in the real app (top navigation + transitions), in its theme.
// The panel sets the page's theme; the controls tune the transitions.
export default { title: 'Pages', parameters: { layout: 'fullscreen' }, argTypes: transitionArgTypes, args: transitionArgs };

${pageStories.join('\n')}
`;

  for (const id of order) {
    const entries = content[id] ?? [];
    if (!entries.length) continue;
    const used = new Set();
    const stories = entries.map(
      (entry) => `export const ${exportName(entry.key, used)} = { ...cardStory(${JSON.stringify(entry.key)}), name: ${JSON.stringify(entry.name)} };`,
    );
    const fileName = `Cards${exportName(id, new Set())}.stories.jsx`;
    files[`home-cards/${fileName}`] = `${HEADER}import { cardStory } from '../../pages/storybook/cardStories.jsx';

// The cards and blocks on this page, in page order. Apply in each writes its config.
export default { title: ${JSON.stringify(`Components/Cards/${pageLabel(id, menu, pages)}`)}, parameters: { layout: 'padded' } };

${stories.join('\n')}
`;
  }
  return files;
}

const fullPath = (name) => (name.startsWith('pages/') ? path.join(pagesDir, name.slice(6)) : path.join(cardsDir, name.slice(11)));

/** Writes the files, touching only those that changed, and removes stale card files. */
export function generateStories({ content } = {}) {
  const files = buildStoryFiles({ menu: readJson(menuFile), pages: readJson(pagesFile), content });
  for (const [name, source] of Object.entries(files)) {
    const file = fullPath(name);
    if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== source) fs.writeFileSync(file, source);
  }
  const keep = new Set(Object.keys(files).map(fullPath));
  for (const name of fs.readdirSync(cardsDir)) {
    const file = path.join(cardsDir, name);
    if (CARD_FILE.test(name) && !keep.has(file) && fs.readFileSync(file, 'utf8').startsWith(HEADER)) fs.rmSync(file);
  }
  return Object.keys(files);
}
